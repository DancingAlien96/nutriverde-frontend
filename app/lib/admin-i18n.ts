export const ADMIN_DICT: Record<Locale, AdminDict> = { en: EN, es: ES };

/** Diccionario del panel en el idioma activo. */
export function useAdminT(): AdminDict {
  const { locale } = useLocale();
  return ADMIN_DICT[locale];
}

/** Convierte el locale guardado en el usuario (EN/ES) al del sitio (en/es). */
export function toSiteLocale(adminLocale?: string | null): Locale {
  return adminLocale?.toUpperCase() === "ES" ? "es" : "en";
}
